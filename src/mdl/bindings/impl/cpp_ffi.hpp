namespace mdl::bindings {

	class CppFfiGenerator final : public BindingGenerator {
	public:
		std::filesystem::path inferBindingsFilename(const std::filesystem::path& outfile) override {
			return outfile.parent_path() / (outfile.stem().string() + ".hpp");
		}

		void generate(const CompilationUnit& unit, const std::filesystem::path& output) override;
	};

} // namespace mdl::bindings

namespace {
	using namespace mdl::bindings::detail;

	inline void generateCppModule(std::ostream& out, std::string_view name, const mdl::ModuleType& mod) {
		out << "/// Wrapper for MDL module '" << name << "'.\n";
		if (!mod.variables.empty()) {
			out << "/// Variables (will be loaded from ArgVals in a future release):";
			for (const auto& [vname, vnode] : mod.variables)
				out << " " << vname << ": " << dtypeStr(mdl::getDataType(vnode.get()));
			out << "\n";
		}
		out << "class " << name << " {\n"
			<< "public:\n"
			<< "    explicit " << name << "(tvm::runtime::Module mod) : _mod(std::move(mod)) {}\n\n";

		for (const auto& [funcName, funcDecl] : mod.functions) {
			out << "    /// " << funcSignatureStr(funcDecl) << "\n"
				<< "    /// \\param _out Pre-allocated output tensor (matching shape and device).\n"
				<< "    void " << funcName << "(";
			bool first = true;
			for (const auto& [pname, pnode] : funcDecl.parameters) {
				if (!first)
					out << ", ";
				out << cppParamType(mdl::getDataType(pnode.get())) << " " << pname;
				first = false;
			}
			out << ", tvm::runtime::NDArray _out) {\n"
				<< "        _mod.GetFunction(\"" << mdl::mangledName(name, funcName) << "\")(";
			first = true;
			for (const auto& [pname, _] : funcDecl.parameters) {
				if (!first)
					out << ", ";
				out << pname;
				first = false;
			}
			out << ", _out);\n"
				<< "    }\n\n";
		}

		out << "private:\n"
			<< "    tvm::runtime::Module _mod;\n"
			<< "};\n\n";
	}
} // namespace

inline void mdl::bindings::CppFfiGenerator::generate(const CompilationUnit& unit, const std::filesystem::path& output) {
	std::ofstream out(output);
	out << "// Generated by mdlc -- do not edit\n"
		<< "#pragma once\n\n"
		<< "#include <tvm/runtime/module.h>\n"
		<< "#include <tvm/runtime/ndarray.h>\n\n"
		<< "namespace mdl {\n\n";

	for (const auto& [name, def] : unit.definitions) {
		if (const auto* mod = std::get_if<mdl::ModuleType>(&def))
			generateCppModule(out, name, *mod);
		/** \todo generate free functions for top-level FunctionDecl **/
	}

	out << "} // namespace mdl\n";
}
