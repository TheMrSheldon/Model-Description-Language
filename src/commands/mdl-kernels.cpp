namespace {
	using namespace mdl::kernels;

	std::string kindName(Artifact::Kind kind) {
		switch (kind) {
		case Artifact::Kind::staticLibrary:
			return "static-library";
		case Artifact::Kind::sharedLibrary:
			return "shared-library";
		case Artifact::Kind::cubin:
			return "cubin";
		case Artifact::Kind::ptx:
			return "ptx";
		}
		return "";
	}

	/** @brief Whether @p artifact can be used on the host, and why not. */
	std::string usability(const Artifact& artifact, const Platform& host) {
		if (!artifact.supported())
			return "not supported yet (" + kindName(artifact.kind) + ")";
		if (!compatible(artifact.platform, host))
			return "not for this host";
		std::error_code ec;
		if (!std::filesystem::is_regular_file(artifact.path, ec))
			return "missing file " + artifact.path.string();
		return "usable";
	}

	/** @brief A CMake target name for @p text (letters, digits, and underscores). */
	std::string cmakeName(const std::string& text) {
		std::string name;
		for (char c : text)
			name += std::isalnum(static_cast<unsigned char>(c)) ? c : '_';
		return name;
	}

	std::string cmakeString(const std::filesystem::path& path) {
		std::string escaped;
		for (char c : path.generic_string()) {
			if (c == '"' || c == '\\' || c == '$')
				escaped += '\\';
			escaped += c;
		}
		return '"' + escaped + '"';
	}

	/**
	 * @brief The link requirements of the packages (`deps`): per package, the artifacts that its implementations can
	 * use on this host, as CMake IMPORTED targets (`mdl_kernel_package_<name>`) or as JSON.
	 */
	int
	deps(const std::vector<std::filesystem::path>& explicitDirs, const std::vector<std::string>& only,
		 const std::string& format) {
		const auto host = hostPlatform();
		const auto found = discover(kernelDirs(explicitDirs, std::nullopt));
		for (const auto& problem : found.problems)
			std::cerr << "mdl-kernels: package skipped: " << problem.str() << "\n";
		nlohmann::json json = nlohmann::json::array();
		std::string cmake =
				"# Generated by mdl-kernels deps: the kernel packages as IMPORTED targets (see docs/kernels.md).\n";
		bool openmp = false;
		std::vector<std::string> missing = only;
		for (const auto& p : found.packages) {
			if (!only.empty() && !std::ranges::contains(only, p.name))
				continue;
			std::erase(missing, p.name);
			std::vector<const Artifact*> usable; // used by an implementation (or a dependency of one), on this host
			std::vector<std::string> pending;
			for (const auto& impl : p.implementations)
				pending.insert(pending.end(), impl.artifacts.begin(), impl.artifacts.end());
			while (!pending.empty()) {
				const auto* a = p.artifact(pending.back());
				pending.pop_back();
				if (a == nullptr || std::ranges::contains(usable, a) || !a->supported() ||
					!compatible(a->platform, host))
					continue;
				usable.push_back(a);
				for (const auto& d : a->dependencies)
					if (d.kind == Dependency::Kind::artifact)
						pending.push_back(d.name);
			}
			nlohmann::json package{{"package", p.name}, {"version", p.version}, {"artifacts", nlohmann::json::array()}};
			const std::string target = "mdl_kernel_package_" + cmakeName(p.name);
			cmake += std::format("\nif(NOT TARGET {})\n\tadd_library({} INTERFACE IMPORTED)\n", target, target);
			for (const auto* a : usable) {
				nlohmann::json deps = nlohmann::json::array();
				const std::string atarget =
						std::format("mdl_kernel_artifact_{}_{}", cmakeName(p.name), cmakeName(a->id));
				cmake += std::format(
						"\tadd_library({} {} IMPORTED)\n\tset_target_properties({} PROPERTIES IMPORTED_LOCATION {})\n",
						atarget, a->kind == Artifact::Kind::sharedLibrary ? "SHARED" : "STATIC", atarget,
						cmakeString(a->path)
				);
				for (const auto& d : a->dependencies) {
					std::string lib;
					switch (d.kind) {
					case Dependency::Kind::systemLibrary:
						lib = d.name;
						deps.push_back("system-library:" + d.name);
						break;
					case Dependency::Kind::runtime:
						lib = "OpenMP::OpenMP_CXX";
						openmp = true;
						deps.push_back("runtime:" + d.name);
						break;
					case Dependency::Kind::artifact:
						lib = std::format("mdl_kernel_artifact_{}_{}", cmakeName(p.name), cmakeName(d.name));
						deps.push_back("artifact:" + d.name);
						break;
					}
					cmake += std::format(
							"\tset_property(TARGET {} APPEND PROPERTY INTERFACE_LINK_LIBRARIES {})\n", atarget, lib
					);
				}
				cmake += std::format("\ttarget_link_libraries({} INTERFACE {})\n", target, atarget);
				package["artifacts"].push_back(
						{{"artifact", a->id},
						 {"path", a->path.string()},
						 {"kind", kindName(a->kind)},
						 {"dependencies", deps}}
				);
			}
			cmake += std::format(
					"\tset_property(GLOBAL PROPERTY MDL_KERNEL_PACKAGE_BUILD_{} IMPORTED)\nendif()\n", p.name
			);
			json.push_back(package);
		}
		for (const auto& name : missing)
			std::cerr << "mdl-kernels: no kernel package " << name << "\n";
		if (format == "json")
			std::cout << json.dump(2) << "\n";
		else
			std::cout << (openmp ? "find_package(OpenMP REQUIRED COMPONENTS CXX)\n" : "") << cmake;
		return missing.empty() ? 0 : 1;
	}

	/** @brief Linker arguments for the libraries of a kernel report (a convenience for builds without CMake). */
	int linkArgs(const std::filesystem::path& reportFile, const std::string& style) {
		nlohmann::json report;
		try {
			std::ifstream in{reportFile};
			report = nlohmann::json::parse(in);
		} catch (const std::exception& e) {
			std::cerr << "mdl-kernels: cannot read " << reportFile.string() << ": " << e.what() << "\n";
			return 1;
		}
		const bool msvc = style == "msvc";
		std::vector<std::string> args, after; // the libraries, then the system libraries and runtimes
		for (const auto& entry : report["link"]) {
			args.push_back(entry["path"].get<std::string>());
			for (const auto& dep : entry["dependencies"]) {
				const auto d = dep.get<std::string>();
				std::string arg;
				if (d.starts_with("system-library:"))
					arg = msvc ? d.substr(15) + ".lib" : "-l" + d.substr(15);
				else if (d == "runtime:openmp")
					arg = msvc ? "/openmp" : "-fopenmp";
				if (!arg.empty() && !std::ranges::contains(after, arg))
					after.push_back(arg);
			}
		}
		args.insert(args.end(), after.begin(), after.end());
		for (size_t i = 0; i < args.size(); ++i)
			std::cout << (i > 0 ? " " : "") << (args[i].find(' ') != std::string::npos ? '"' + args[i] + '"' : args[i]);
		std::cout << "\n";
		return 0;
	}

	int
	list(const std::vector<std::filesystem::path>& explicitDirs, const std::optional<std::filesystem::path>& source) {
		const auto host = hostPlatform();
		const auto dirs = kernelDirs(explicitDirs, source);
		const auto found = discover(dirs);

		std::cout << std::format("Host: {}\n\nKernel directories (most specific first):\n", host.str());
		if (dirs.empty())
			std::cout << "  (none)\n";
		for (const auto& d : dirs)
			std::cout << std::format("  {:<14} {}\n", str(d.origin), d.path.string());

		std::cout << "\nPackages:\n";
		if (found.packages.empty())
			std::cout << "  (none)\n";
		for (const auto& p : found.packages) {
			std::cout << std::format("  {} {}  ({})\n", p.name, p.version, p.directory.string());
			if (!p.description.empty())
				std::cout << std::format("    {}\n", p.description);
			for (const auto& a : p.artifacts)
				std::cout << std::format(
						"    artifact {} [{}, {}]: {}\n", a.id, kindName(a.kind),
						a.supported() ? a.platform.str() : "device " + a.deviceArch, usability(a, host)
				);
			for (const auto& impl : p.implementations)
				std::cout << std::format(
						"    implementation {} (pattern {}, priority {}, symbol {})\n", impl.id, impl.pattern,
						impl.priority, impl.symbol
				);
		}
		for (const auto& [hidden, by] : found.hidden)
			std::cout << std::format(
					"  hidden: {} {} in {} (by the package in {})\n", hidden.name, hidden.version,
					hidden.directory.string(), by.string()
			);

		if (!found.problems.empty()) {
			std::cout << "\nProblems (these packages are skipped):\n";
			for (const auto& problem : found.problems)
				std::cout << "  " << problem.str() << "\n";
		}
		return found.problems.empty() ? 0 : 1;
	}
} // namespace

int main(int argc, char* argv[]) {
	CLI::App app{"mdl-kernels -- inspects the kernel packages of the kernel directories"};
	app.set_version_flag("--version", std::string{mdl::version});
	app.require_subcommand(1);

	std::vector<std::filesystem::path> explicitDirs;
	app.add_option(
			"--kernels-dir", explicitDirs,
			"A kernel directory (searched first; repeatable). Then: the project's .mdl/kernels, the user's directory, "
			"MDL_KERNELS_PATH, and the installation's share/mdl/kernels."
	);

	std::optional<std::filesystem::path> source;
	auto* listCommand = app.add_subcommand("list", "Lists the kernel directories, packages, and their problems");
	listCommand->add_option("source", source, "A source file: its project's .mdl/kernels is searched too");

	std::vector<std::string> depsPackages;
	std::string depsFormat = "cmake";
	auto* depsCommand = app.add_subcommand(
			"deps", "Prints the link requirements of the kernel packages for this host (CMake IMPORTED targets or JSON)"
	);
	depsCommand->add_option("--kernel-package", depsPackages, "Only this package (repeatable)");
	depsCommand->add_option("--format", depsFormat, "cmake (default) or json")->check(CLI::IsMember({"cmake", "json"}));
	std::filesystem::path reportFile;
	std::string linkStyle = "gnu";
	auto* linkCommand = app.add_subcommand(
			"link-args", "Prints linker arguments for the libraries of a kernel report (mdlc --kernel-report)"
	);
	linkCommand->add_option("report", reportFile, "The kernel report (JSON)")->required();
	linkCommand->add_option("--style", linkStyle, "gnu (default) or msvc")->check(CLI::IsMember({"gnu", "msvc"}));

	// check and dump compile the model like mdlc (with the same options) up to the matching boundary.
	CompileArgs checkArgs, dumpArgs;
	bool explainAll = false;
	auto* checkCommand = app.add_subcommand(
			"check", "Matches the kernel packages against a model: the selected implementations (no code is generated)"
	);
	auto* checkConfig = addCompileOptions(*checkCommand, checkArgs);
	checkCommand->add_flag(
			"--explain", explainAll,
			"Show every candidate with the verdict of each constraint and why it is (not) selected"
	);
	auto* dumpCommand = app.add_subcommand(
			"dump", "Prints the model's Relax module at the matching boundary (what patterns match)"
	);
	auto* dumpConfig = addCompileOptions(*dumpCommand, dumpArgs);

	try {
		app.parse(argc, argv);
	} catch (const CLI::ParseError& e) {
		return app.exit(e);
	}
	if (listCommand->parsed())
		return list(explicitDirs, source);
	if (depsCommand->parsed())
		return deps(explicitDirs, depsPackages, depsFormat);
	if (linkCommand->parsed())
		return linkArgs(reportFile, linkStyle);
	auto inspect = [&](CompileArgs& args, CLI::Option* config, mdl::CompileOptions::KernelInspection mode) {
		if (config->count() > 0)
			args.argvals = config->as<std::string>();
		args.compileOpts.kernelDirs.insert(
				args.compileOpts.kernelDirs.begin(), explicitDirs.begin(), explicitDirs.end()
		);
		args.compileOpts.inspectKernels = mode;
		args.compileOpts.inspectOut = &std::cout;
		try {
			runCompileCommand(args);
		} catch (const std::exception& e) {
			std::cerr << "mdl-kernels: error: " << e.what() << "\n";
			return 1;
		}
		return 0;
	};
	using Inspection = mdl::CompileOptions::KernelInspection;
	if (checkCommand->parsed())
		return inspect(checkArgs, checkConfig, explainAll ? Inspection::explain : Inspection::brief);
	if (dumpCommand->parsed())
		return inspect(dumpArgs, dumpConfig, Inspection::dump);
	return 0;
}
