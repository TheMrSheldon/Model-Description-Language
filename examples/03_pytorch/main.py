# Calls the compiled model from PyTorch through the generated bindings.
#   pip install apache-tvm-ffi torch
#   python main.py <build dir>/examples/03_pytorch
import sys
from pathlib import Path

import torch

build_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("build/examples/03_pytorch")
sys.path.insert(0, str(build_dir / "mdl" / "03_pytorch"))
from model_pytorch import Linear  # noqa: E402  (generated by mdlc)

W = torch.arange(3 * 8, dtype=torch.float32).reshape(3, 8)
b = torch.arange(3, dtype=torch.float32)
x = torch.arange(8, dtype=torch.float32)

model = Linear(str(build_dir / "lib03_pytorch.so"), {"W": W, "b": b})
out = torch.empty(3, dtype=torch.float32)
model.forward(x, out)
print("Expected output:", W @ x + b)
print("Output:         ", out)
