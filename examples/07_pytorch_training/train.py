"""
Trains the compiled BERT classifier with PyTorch (proof of concept for gradient builds in PyTorch).

The model is `BertForSequenceClassification` of examples/02_transformer/model.dlm (a tiny BERT, see
model_cls_tiny.yml), compiled as a masked gradient build: `logits` saves its intermediates in a context buffer and
`logits_backward` computes the weight gradients from it. The generated binding wraps both in a torch.autograd.Function
(`logits_autograd`), so the loss is computed in PyTorch, `loss.backward()` runs the compiled backward pass, and a
PyTorch optimizer updates the weights.

The script
  1. compares the logits and the gradients of the first batch with Hugging Face's BertForSequenceClassification
     (same initial weights) under PyTorch autograd,
  2. trains the compiled model and the Hugging Face model side by side with AdamW on a synthetic task (classify which
     third of the vocabulary most valid tokens come from; the sequences are padded with random tokens that the mask
     must hide) and reports the loss and accuracy of both.

  pip install apache-tvm-ffi torch transformers
  python train.py <build dir>/examples/07_pytorch_training
"""
import argparse
import sys
from pathlib import Path

import torch
from transformers import BertConfig, BertForSequenceClassification

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "02_transformer"))
from export_bert_reference import mdl_weights  # noqa: E402

VOCAB, POSITIONS, CLASSES = 100, 16, 3


def make_batch(generator: torch.Generator, batch: int, seq: int):
    """Sequences of 4..seq valid tokens from 1..99, padded with random tokens; the label is the majority third."""
    lengths = torch.randint(4, seq + 1, (batch,), generator=generator)
    ids = torch.randint(1, VOCAB, (batch, seq), generator=generator)
    mask = torch.arange(seq)[None, :] < lengths[:, None]
    buckets = (ids - 1) * CLASSES // (VOCAB - 1)
    counts = torch.stack([((buckets == c) & mask).sum(1) for c in range(CLASSES)], 1)
    labels = counts.argmax(1)
    return ids, mask, labels


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("build_dir", nargs="?", default="build/examples/07_pytorch_training")
    parser.add_argument("--steps", type=int, default=300)
    parser.add_argument("--batch", type=int, default=32)
    parser.add_argument("--seq", type=int, default=POSITIONS)
    parser.add_argument("--lr", type=float, default=1e-3)
    args = parser.parse_args()

    build_dir = Path(args.build_dir)
    sys.path.insert(0, str(build_dir / "mdl" / "07_pytorch_training"))
    from model_pytorch import BertForSequenceClassification as Compiled  # generated by mdlc

    torch.manual_seed(0)
    config = BertConfig(hidden_size=32, num_attention_heads=4, intermediate_size=64, num_hidden_layers=2,
                        vocab_size=VOCAB, max_position_embeddings=POSITIONS, num_labels=CLASSES,
                        hidden_dropout_prob=0.0, attention_probs_dropout_prob=0.0)
    hf = BertForSequenceClassification(config)

    # The compiled model's weights: leaf tensors that require gradients, initialized like the HF model.
    initial = {f"bert.{k}": v for k, v in mdl_weights(hf.bert, config.num_hidden_layers).items()}
    initial["classifier.W"] = hf.classifier.weight.detach()
    initial["classifier.b"] = hf.classifier.bias.detach()
    weights = {k: torch.nn.Parameter(v.clone()) for k, v in initial.items()}
    model = Compiled(str(build_dir / "lib07_pytorch_training.so"), weights)

    def logits_of(ids, mask):
        batch, seq = ids.shape
        positions = torch.arange(seq, dtype=torch.int32).expand(batch, seq).contiguous()
        types = torch.zeros(batch, seq, dtype=torch.int32)
        return model.logits_autograd(ids.int(), types, positions, mask)

    def hf_logits_of(ids, mask):
        return hf(input_ids=ids, attention_mask=mask.long()).logits

    # 1. Logits and gradients of one batch against Hugging Face.
    generator = torch.Generator().manual_seed(1)
    ids, mask, labels = make_batch(generator, args.batch, args.seq)
    logits = logits_of(ids, mask)
    torch.nn.functional.cross_entropy(logits, labels).backward()
    hf_logits = hf_logits_of(ids, mask)
    torch.nn.functional.cross_entropy(hf_logits, labels).backward()
    class Gradients:  # the HF gradients under the MDL weight paths (mdl_weights maps named_parameters)
        def named_parameters(self):
            return ((name, p.grad) for name, p in hf.bert.named_parameters())

    hf_grads = {f"bert.{k}": v for k, v in mdl_weights(Gradients(), config.num_hidden_layers).items()}
    hf_grads["classifier.W"] = hf.classifier.weight.grad
    hf_grads["classifier.b"] = hf.classifier.bias.grad
    logit_error = (logits - hf_logits).abs().max().item()
    # Relative to the largest gradient of each weight; at least 1e-6, since some gradients are zero analytically (the
    # key biases: softmax is invariant to shifts that are the same for all keys) and both sides compute rounding noise.
    grad_error = max(((weights[p].grad - hf_grads[p]).abs().max() / hf_grads[p].abs().max().clamp_min(1e-6)).item()
                     for p in weights)
    print(f"logits vs Hugging Face: max abs error {logit_error:.2e}")
    print(f"gradients vs Hugging Face ({len(weights)} weights): max relative error {grad_error:.2e}")

    # Padding must not matter: other padding tokens give the same logits.
    other = torch.where(mask, ids, torch.randint(1, VOCAB, ids.shape, generator=generator))
    padding_error = (logits_of(other, mask) - logits).abs().max().item()
    print(f"logits with other padding tokens: max abs difference {padding_error:.2e}")

    # 2. Training side by side.
    optimizer = torch.optim.AdamW(weights.values(), lr=args.lr)
    hf_optimizer = torch.optim.AdamW(hf.parameters(), lr=args.lr)
    for step in range(1, args.steps + 1):
        ids, mask, labels = make_batch(generator, args.batch, args.seq)
        optimizer.zero_grad()
        loss = torch.nn.functional.cross_entropy(logits := logits_of(ids, mask), labels)
        loss.backward()
        optimizer.step()
        hf_optimizer.zero_grad()
        hf_loss = torch.nn.functional.cross_entropy(hf_logits_of(ids, mask), labels)
        hf_loss.backward()
        hf_optimizer.step()
        if step % 50 == 0 or step == 1:
            accuracy = (logits.argmax(1) == labels).float().mean().item()
            print(f"step {step:4d}: loss {loss.item():.4f} (Hugging Face {hf_loss.item():.4f}), "
                  f"accuracy {accuracy:.2f}")

    with torch.no_grad():
        ids, mask, labels = make_batch(torch.Generator().manual_seed(1234), 1024, args.seq)
        accuracy = (logits_of(ids, mask).argmax(1) == labels).float().mean().item()
    print(f"test accuracy (1024 sequences): {accuracy:.3f} (chance {1 / CLASSES:.3f})")

    ok = logit_error < 1e-4 and grad_error < 1e-3 and padding_error < 1e-5 and accuracy > 0.6
    print("OK" if ok else "FAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
